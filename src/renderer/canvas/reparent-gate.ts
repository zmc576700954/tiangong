/**
 * 重挂（拖拽换父）开关的判定 —— 纯函数，单独成模块就是为了能被直接单测。
 *
 * 为什么不放在 GraphCanvas.tsx 里导出：那是个两千行的组件模块，单测拉起它
 * 要连带挂 ReactFlow / store / i18n —— 而这条规则本身零依赖。
 */

/** 布局模式三态：树形 / 力导向 / **还没从 localStorage 读回来** */
export type LayoutMode = 'tree' | 'force' | null

/**
 * 当前布局模式下是否允许拖拽重挂。
 *
 * ⚠️ **必须 fail closed**（`=== 'tree'`，**不是** `!== 'force'`）：
 * 模式还没读回来（`null`）的那一小段时间里，`!== 'force'` 会把它当成树形 →
 * **力导向项目的重挂在那段时间里是开着的** —— 而 R-38 明确禁止力导向下重挂
 * （力导向模式一次拖拽结束会把所有节点的仿真坐标整体写回数据库，
 *  会覆盖掉重挂算出来的锚点位置与整棵子树的平移结果）。
 * `=== 'tree'` 让它在这段时间里**关着**。
 *
 * 代价：启动与切图时各有**一帧左右**重挂不可用（读回模式后就有了）—— 零代价。
 *
 * ⚠️ 这是「缺省即危险」的开关，不是随手写的 if：
 * 它必须是一个**能被单测直接调用**的纯函数。否则把 `=== 'tree'` 改回
 * `!== 'force'` 会悄无声息地通过全部 e2e（变异验证：改坏之后 13 条结构编辑
 * e2e 照样全绿 —— 这条不变量当时没有任何自动化覆盖）。
 */
export function isReparentEnabled(layoutMode: LayoutMode): boolean {
  return layoutMode === 'tree'
}
